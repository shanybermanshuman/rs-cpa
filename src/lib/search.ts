/**
 * בריחה מתווי הג'וקר של LIKE.
 *
 * `contains` של Prisma מעביר את הערך כפי שהוא ל-LIKE ואינו מנטרל `%` ו-`_`,
 * ולכן חיפוש של "%" היה מחזיר את **כל** הלקוחות במקום כלום. Postgres משתמש
 * בברירת מחדל בלוכסן אחורי כתו בריחה.
 */
export function escapeLike(value: string) {
  return value.replace(/[\\%_]/g, (ch) => `\\${ch}`);
}

/**
 * ספרות הטלפון בלבד, לחיפוש שאינו תלוי פורמט.
 *
 * הטלפון נשמר כפי שהוקלד, ולכן אותו מספר עצמו יכול להיות שמור כ-052-1234567,
 * 052 123 4567 או ‎+972-52-1234567. הנרמול מוריד מפרידים ומחליף קידומת
 * בינלאומית באפס המקומי, כך ששלוש הצורות משתוות לאותה מחרוזת ספרות.
 * אותו נרמול בדיוק מבוצע בצד ה-SQL על העמודה השמורה.
 */
export function phoneSearchDigits(value: string) {
  return value.replace(/\D/g, "").replace(/^(?:00)?972/, "0");
}
